"""The tick: decide which day is due, generate it, record it.

This is the piece that turns a manual CLI into an unattended job, and every design
choice here is about surviving the ways an unattended job goes wrong:

* **The wall clock lives here, and only here.** ``daily/`` reads no clock on purpose,
  so that a day's artifact is reproducible. This module is the single place allowed to
  ask "what time is it", and it converts that answer into an explicit date before
  handing anything to the generator.
* **One day at a time, recorded one day at a time.** The ledger is saved after each
  day completes, so a crash on day 4 of 5 keeps days 1-3 done. Marking the whole batch
  at the end would throw away work that had already succeeded.
* **Backfill is bounded and recent-first.** The machine being off for a day or a week
  is normal; being off for a year is not, and silently generating 365 days would turn a
  recovery into an outage. The cap keeps the newest days and reports how many older
  ones were left behind rather than pretending they were handled.
* **First run generates one day.** An empty ledger means "nothing has been generated",
  not "a month is missing"; backfilling history on a first run would be a surprise
  nobody asked for. Generating history is a deliberate act, and the daily CLI already
  does it with ``--from/--to``.
"""

from __future__ import annotations

import json
import shutil
from collections.abc import Callable
from dataclasses import dataclass
from datetime import date, datetime, timedelta
from pathlib import Path

from tools.synthetic_clouds.schedule.config import ScheduleConfig
from tools.synthetic_clouds.schedule.state import RunRecord, RunState, load_state, save_state

#: Appended one JSON line per tick. Operational log, not an artifact: nothing here
#: reaches an export, so a wall-clock instant cannot leak into the generated bytes.
DEFAULT_LOG_NAME = "runs.log"

_STATUS_OK = "ok"
_STATUS_UP_TO_DATE = "up-to-date"
_STATUS_FAILED = "failed"
_STATUS_DISABLED = "disabled"


class TickError(Exception):
    """Raised when a tick cannot proceed at all (as opposed to a day failing)."""


#: A per-day generator: renders one simulated day and returns its artifact count.
#: ``tick`` takes one so tests can exercise planning, ledger updates and failure
#: handling without rendering a real estate, which costs minutes per day.
DayGenerator = Callable[[date], int]


@dataclass(frozen=True, slots=True)
class TickPlan:
    """Which days a tick should generate, and what it chose not to."""

    target_day: date
    days: tuple[date, ...]
    truncated: int
    """Missing days older than the backfill window that were left alone."""

    @property
    def first_day(self) -> date | None:
        return self.days[0] if self.days else None


@dataclass(frozen=True, slots=True)
class TickResult:
    """What a tick did, in the terms an operator needs to read."""

    status: str
    target_day: date
    generated: tuple[date, ...]
    artifacts: int
    truncated: int
    errors: tuple[str, ...]
    pruned: tuple[date, ...] = ()

    @property
    def ok(self) -> bool:
        return self.status in {_STATUS_OK, _STATUS_UP_TO_DATE, _STATUS_DISABLED}


def plan_prune(target_day: date, completed: tuple[date, ...], *, retention_days: int | None) -> tuple[date, ...]:
    """Return the days retention should delete: those before the kept window.

    The window is the ``retention_days`` most recent days *ending at the target*, so a
    run that is behind does not delete days it has just decided are still worth having.
    ``None`` means keep everything, which is the default.
    """
    if retention_days is None:
        return ()
    if retention_days < 1:
        raise TickError("retention_days must be >= 1 or None")
    cutoff = target_day - timedelta(days=retention_days - 1)
    return tuple(sorted(day for day in completed if day < cutoff))


def prune_days(out_root: Path, days: tuple[date, ...]) -> tuple[tuple[date, ...], tuple[str, ...]]:
    """Delete each day's directory under ``out_root``; return (deleted, errors).

    A day whose directory is already gone counts as deleted: the desired end state is
    reached either way. A day that cannot be deleted is reported and left in the ledger,
    because claiming to have pruned it while the bytes remain would be the same lie in
    the opposite direction.
    """
    deleted: list[date] = []
    errors: list[str] = []
    for day in days:
        directory = out_root / day.isoformat()
        if not directory.exists():
            deleted.append(day)
            continue
        try:
            shutil.rmtree(directory)
        except OSError as exc:
            errors.append(f"prune {day.isoformat()}: {type(exc).__name__}: {exc}")
            continue
        deleted.append(day)
    return tuple(deleted), tuple(errors)


def plan_backfill(
    target_day: date,
    completed: tuple[date, ...],
    *,
    max_days: int,
    force: bool = False,
    only: date | None = None,
) -> TickPlan:
    """Return the days to generate for ``target_day``, given the ledger.

    Pure on purpose: the whole recovery policy -- first run, up-to-date, gap, the cap,
    and the explicit ``only`` day -- is decided here, where a test can enumerate every
    case without touching a clock or a filesystem.
    """
    if max_days < 1:
        raise TickError("max_days must be >= 1")

    if only is not None:
        # An explicit day is an operator instruction, not a recovery decision: it is
        # generated even out of order, and `force` decides only whether a day already in
        # the ledger is redone.
        days = () if (only in set(completed) and not force) else (only,)
        return TickPlan(target_day=only, days=days, truncated=0)

    if not completed:
        return TickPlan(target_day=target_day, days=(target_day,), truncated=0)

    newest = max(completed)
    if target_day <= newest:
        # Already current, or the clock moved backwards (timezone change, NTP step,
        # a restore). Regenerating the newest day in that case is the one action that
        # cannot be justified, so a forced run is the only way in.
        if force and target_day == newest:
            return TickPlan(target_day=target_day, days=(target_day,), truncated=0)
        return TickPlan(target_day=target_day, days=(), truncated=0)

    known = set(completed)
    candidates = [
        newest + timedelta(days=offset)
        for offset in range(1, (target_day - newest).days + 1)
        if newest + timedelta(days=offset) not in known
    ]
    if force and target_day in known:
        candidates.append(target_day)

    if len(candidates) > max_days:
        truncated = len(candidates) - max_days
        return TickPlan(target_day=target_day, days=tuple(candidates[-max_days:]), truncated=truncated)
    return TickPlan(target_day=target_day, days=tuple(candidates), truncated=0)


def target_day_for(config: ScheduleConfig, now: datetime) -> date:
    """Return the newest day whose export is complete at ``now``.

    ``lag_days`` encodes FR-B2: a charge dated ``D`` is first exported at ``D + 1``
    ``00:00 UTC``. Interpreting ``now`` in the configured zone is what makes the day
    boundary follow that zone rather than the machine's.
    """
    local = now.astimezone(config.zone())
    return local.date() - timedelta(days=config.lag_days)


def _log_line(path: Path, record: RunRecord) -> None:
    """Append one JSON line to the run log, creating its directory if needed."""
    path.parent.mkdir(parents=True, exist_ok=True)
    with path.open("a", encoding="utf-8") as handle:
        handle.write(json.dumps(record.to_document(), sort_keys=True) + "\n")


def tick(
    config: ScheduleConfig,
    *,
    now: datetime,
    state_path: Path,
    out_root: Path,
    log_path: Path,
    force: bool = False,
    generate: DayGenerator | None = None,
    only_day: date | None = None,
) -> TickResult:
    """Generate every due day, recording each one as it completes; then prune.

    ``generate`` exists so tests can drive the whole tick -- planning, ledger updates,
    pruning, failure handling -- without rendering a real estate, which costs minutes.
    The default renders through the same ``run_days`` the one-off generator uses.

    Pruning happens on **every** tick, including the ones with nothing to generate. A
    machine that is always current would otherwise never prune, and the disk would fill
    at the same rate as one that is always behind.
    """
    if not config.enabled:
        return TickResult(
            status=_STATUS_DISABLED,
            target_day=only_day if only_day is not None else target_day_for(config, now),
            generated=(),
            artifacts=0,
            truncated=0,
            errors=(),
        )

    state = load_state(state_path)
    plan = plan_backfill(
        target_day_for(config, now),
        state.completed_days(),
        max_days=config.backfill_max_days,
        force=force,
        only=only_day,
    )
    at = now.isoformat()

    renderer = _renderer_for(config, generate, out_root)
    generated: list[date] = []
    artifacts = 0
    generation_errors: list[str] = []

    for day in plan.days:
        try:
            count = renderer(day)
        except Exception as exc:  # noqa: BLE001 - a failed day is recorded, not swallowed
            generation_errors.append(f"{day.isoformat()}: {type(exc).__name__}: {exc}")
            break
        generated.append(day)
        artifacts += count
        # Saved per day, not per batch: a crash on the next day must not discard the
        # record of the days that already succeeded.
        state = state.with_day(day, artifacts=count, at=at)
        state = state.with_run(
            RunRecord(
                at=at,
                target_day=plan.target_day.isoformat(),
                status=_STATUS_OK,
                generated=tuple(item.isoformat() for item in generated),
            )
        )
        save_state(state, state_path)

    pruned, prune_errors = _apply_retention(config, state, plan.target_day, out_root)
    state = state.without_days(pruned)

    # The status reports the GENERATION outcome. A day that could not be deleted is a
    # maintenance problem, reported in `errors`, not a reason to call the data run failed.
    status = _STATUS_FAILED if generation_errors else (_STATUS_OK if plan.days else _STATUS_UP_TO_DATE)
    final = RunRecord(
        at=at,
        target_day=plan.target_day.isoformat(),
        status=status,
        generated=tuple(item.isoformat() for item in generated),
        errors=(*generation_errors, *prune_errors),
        pruned=tuple(item.isoformat() for item in pruned),
    )
    state = state.with_run(final)
    save_state(state, state_path)
    _log_line(log_path, final)

    return TickResult(
        status=status,
        target_day=plan.target_day,
        generated=tuple(generated),
        artifacts=artifacts,
        truncated=plan.truncated,
        errors=(*generation_errors, *prune_errors),
        pruned=pruned,
    )


def _apply_retention(
    config: ScheduleConfig,
    state: RunState,
    target_day: date,
    out_root: Path,
) -> tuple[tuple[date, ...], tuple[str, ...]]:
    """Delete the day directories retention no longer keeps; return (pruned, errors)."""
    doomed = plan_prune(target_day, state.completed_days(), retention_days=config.retention_days)
    if not doomed:
        return (), ()
    return prune_days(out_root, doomed)


def plan_target_day(config: ScheduleConfig, now: datetime) -> date:
    """Return the day this tick is aiming at: ``now`` in the configured zone, minus lag."""
    return target_day_for(config, now)


def _renderer_for(config: ScheduleConfig, generate: DayGenerator | None, out_root: Path) -> DayGenerator:
    """Return the per-day generator: the injected one, or the real renderer pipeline."""
    if generate is not None:
        return generate

    # Imported here, not at module import: this pulls pandas, pyarrow and every
    # renderer module, and `status` / `config show` must stay cheap to run.
    from tools.synthetic_clouds.daily.emit import run_days

    def _render(day: date) -> int:
        written = run_days(
            config.seed,
            config.profile,
            config.currency,
            (day,),
            out_root=out_root,
            renderers=config.renderers,
        )
        return len(written)

    return _render


